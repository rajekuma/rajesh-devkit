#!/bin/bash
# Regenerates each case's scaffold.sh as a self-contained script: the shared
# base fixture inlined, then the case-specific tail from <case>/scaffold.tail.sh.
# The official runner only ever sees a case's own scaffold.sh, so the
# composition happens here, once, and the output is committed.
#
#   bash evals/_shared/make-scaffolds.sh
set -e
cd "$(dirname "$0")/.."
BASE=$(cat _shared/base-fixture.sh)
for tail in */scaffold.tail.sh; do
  case_dir=$(dirname "$tail")
  {
    echo '#!/bin/bash'
    echo "# Generated by evals/_shared/make-scaffolds.sh - edit scaffold.tail.sh, not this."
    echo 'set -e'
    echo "$BASE"
    echo
    cat "$tail"
  } > "$case_dir/scaffold.sh"
  echo "wrote $case_dir/scaffold.sh"
done
